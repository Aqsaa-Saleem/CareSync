export const getActivitiesByCategory = (category: string): Activity[] =>
  activities.filter((a) => a.category === category);

export const getActivitiesByAge = (age: number): Activity[] =>
  activities.filter((a) => {
    const [min, max] = a.ageRange.split('–').map(Number);
    return age >= min && age <= max;
  });

export const getTodayActivities = (): Activity[] => {
  const today = new Date().getDay();
  const shuffled = [...activities].sort((a, b) => {
    const hashA = a.id.split('').reduce((acc, c, i) => acc + c.charCodeAt(0) * (i + 1), 0);
    const hashB = b.id.split('').reduce((acc, c, i) => acc + c.charCodeAt(0) * (i + 1), 0);
    return (hashA + today) % 7 - (hashB + today) % 7;
  });
  return shuffled.slice(0, 3);
};

